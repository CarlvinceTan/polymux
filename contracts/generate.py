#!/usr/bin/env python3
"""Generate the wire representations from polymux.schema.json without dependencies."""
import argparse
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCHEMA = json.loads((ROOT / 'contracts/polymux.schema.json').read_text())
SWIFT = ROOT / 'packages/PolymuxKit/Sources/PolymuxKit/Contract.swift'
GO = ROOT / 'apps/server/internal/contract/types.go'
HUB = ROOT / 'plugins/hub/internal/contract/types.go'
GRAPH = ROOT / 'plugins/graph-visualiser/internal/contract/types.go'
GRAPH_TYPES = ('WorkBlock', 'WorkDetail', 'WorkNode', 'WorkWire', 'WorkGraph', 'WorkReport')

def swift_type(field):
    if '$ref' in field:
        name = field['$ref'].split('/')[-1]
        return 'WireError' if name == 'Error' else name
    kind = field['type']
    if kind == 'array':
        return f"[{swift_type(field['items'])}]"
    if kind == 'object':
        return f"[String: {swift_type(field['additionalProperties'])}]"
    return {'string':'String','integer':'Int64','number':'Double','boolean':'Bool'}[kind]

def go_type(field):
    if '$ref' in field:
        return field['$ref'].split('/')[-1]
    if 'x-go-type' in field:
        return field['x-go-type']
    kind = field['type']
    if kind == 'array':
        return '[]' + go_type(field['items'])
    if kind == 'object':
        return 'map[string]' + go_type(field['additionalProperties'])
    return {'string':'string','integer':'int64','number':'float64','boolean':'bool'}[kind]

def swift_default(field):
    if 'x-swift-default' in field:
        return field['x-swift-default']
    if '$ref' in field:
        return None
    return {'string':'""','integer':'0','number':'0','boolean':'false','array':'[]','object':'[:]'}[field['type']]

INITIALISMS = {'html': 'HTML', 'id': 'ID', 'url': 'URL', 'http': 'HTTP'}

def go_name(text):
    return ''.join(INITIALISMS.get(word, word[:1].upper() + word[1:]) for word in text.replace('.', '_').split('_'))

def go_enums(name, fields):
    lines = []
    for key, field in fields.items():
        values = [value for value in field.get('enum', []) if value]
        if values:
            lines.extend(f'\t{name}{go_name(key)}{go_name(value)} = "{value}"' for value in values)
    return ['const ('] + lines + [')', ''] if lines else []

SWIFT_KEYWORDS = {'default', 'case', 'in', 'is', 'as', 'self', 'true', 'false', 'nil', 'repeat', 'return', 'import', 'func', 'let', 'var', 'class', 'struct', 'enum', 'protocol', 'extension', 'switch', 'where', 'while', 'for', 'if', 'else', 'do', 'try', 'throw', 'throws', 'catch', 'guard', 'defer', 'break', 'continue', 'fallthrough', 'init', 'deinit', 'subscript', 'operator', 'static', 'public', 'private', 'internal', 'super', 'Any', 'Type', 'inout', 'associatedtype', 'typealias'}

def swift_enums(name, fields):
    lines = []
    for key, field in fields.items():
        values = [value for value in field.get('enum', []) if value]
        if not values:
            continue
        lines.append(f'public enum {name}{go_name(key)} {{')
        for value in values:
            first, *rest = value.replace('.', '_').split('_')
            member = first.lower() + go_name('_'.join(rest))
            if member in SWIFT_KEYWORDS:
                member = f'`{member}`'
            lines.append(f'    public static let {member} = "{value}"')
        lines.extend(['}', ''])
    return lines

def generate():
    swift = ['// Generated by contracts/generate.py. Edit polymux.schema.json instead.', 'import Foundation', '']
    go = ['// Code generated by contracts/generate.py; DO NOT EDIT.', 'package contract', '']
    hub = list(go)
    graph = list(go)
    for original, definition in SCHEMA['$defs'].items():
        name = 'WireError' if original == 'Error' else original
        fields = definition['properties']
        required = definition['required']
        swift.append(f'public struct {name}: Codable, Hashable, Sendable {{')
        start = len(go)
        go.append(f'type {original} struct {{')
        params = []
        for key, field in fields.items():
            optional = key not in required
            swift_optional = optional or field.get('x-swift-optional', False)
            typ = swift_type(field) + ('?' if swift_optional else '')
            swift.append(f'    public var {key}: {typ}')
            default = 'nil' if swift_optional else swift_default(field)
            params.append(f'{key}: {typ}' + (f' = {default}' if default is not None else ''))
            gt = go_type(field)
            if optional and field.get('type') not in ('array', 'object') and not field.get('x-go-value', False):
                gt = '*' + gt
            gname = key[0].upper() + key[1:]
            if key == 'id':
                gname = 'ID'
            if key == 'url':
                gname = 'URL'
            go.append(f'\t{gname} {gt} `json:"{key}' + (',omitempty' if optional else '') + '"`')
        swift.extend(['', '    public init(', '        ' + ',\n        '.join(params), '    ) {'])
        swift.extend(f'        self.{key} = {key}' for key in fields)
        swift.extend(['    }', '}', ''])
        swift.extend(swift_enums(name, fields))
        go.extend(['}', ''])
        go.extend(go_enums(original, fields))
        if original.startswith('Hub'):
            hub.extend(go[start:])
        if original in GRAPH_TYPES:
            graph.extend(go[start:])
    return '\n'.join(swift), '\n'.join(go), '\n'.join(hub), '\n'.join(graph)

parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true', help='Fail if generated files differ from schema')
args = parser.parse_args()
swift, go, hub, graph = generate()
go, hub, graph = (subprocess.run(['gofmt'], input=text, text=True, check=True, capture_output=True).stdout for text in (go, hub, graph))
outputs = {SWIFT:swift, GO:go, HUB:hub, GRAPH:graph}
if args.check:
    stale = [str(path.relative_to(ROOT)) for path, value in outputs.items() if not path.exists() or path.read_text() != value]
    if stale:
        raise SystemExit('Stale generated files: ' + ', '.join(stale))
else:
    for path, value in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(value)

#!/usr/bin/env python3
"""Generate the two wire representations from polymux.schema.json without dependencies."""
import argparse
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCHEMA = json.loads((ROOT / 'contracts/polymux.schema.json').read_text())
SWIFT = ROOT / 'packages/PolymuxKit/Sources/PolymuxKit/Contract.swift'
GO = ROOT / 'apps/server/internal/contract/types.go'

def swift_type(field):
    if '$ref' in field:
        name = field['$ref'].split('/')[-1]
        return 'WireError' if name == 'Error' else name
    kind = field['type']
    if kind == 'array':
        return f"[{swift_type(field['items'])}]"
    return {'string':'String','integer':'Int64','number':'Double','boolean':'Bool'}[kind]

def go_type(field):
    if '$ref' in field:
        return field['$ref'].split('/')[-1]
    kind = field['type']
    if kind == 'array':
        return '[]' + go_type(field['items'])
    return {'string':'string','integer':'int64','number':'float64','boolean':'bool'}[kind]

def swift_default(field):
    if '$ref' in field:
        return None
    return {'string':'""','integer':'0','number':'0','boolean':'false','array':'[]'}[field['type']]

def generate():
    swift = ['// Generated by contracts/generate.py. Edit polymux.schema.json instead.', 'import Foundation', '']
    go = ['// Code generated by contracts/generate.py; DO NOT EDIT.', 'package contract', '']
    for original, definition in SCHEMA['$defs'].items():
        name = 'WireError' if original == 'Error' else original
        fields = definition['properties']
        required = definition['required']
        swift.append(f'public struct {name}: Codable, Hashable, Sendable {{')
        go.append(f'type {original} struct {{')
        params = []
        for key, field in fields.items():
            optional = key not in required
            typ = swift_type(field) + ('?' if optional else '')
            swift.append(f'    public var {key}: {typ}')
            default = 'nil' if optional else swift_default(field)
            params.append(f'{key}: {typ}' + (f' = {default}' if default is not None else ''))
            gt = go_type(field)
            if optional and field.get('type') != 'array':
                gt = '*' + gt
            gname = key[0].upper() + key[1:]
            if key == 'id':
                gname = 'ID'
            if key == 'url':
                gname = 'URL'
            go.append(f'\t{gname} {gt} `json:"{key}' + (',omitempty' if optional else '') + '"`')
        swift.extend(['', '    public init(', '        ' + ',\n        '.join(params), '    ) {'])
        swift.extend(f'        self.{key} = {key}' for key in fields)
        swift.extend(['    }', '}', ''])
        go.extend(['}', ''])
    return '\n'.join(swift), '\n'.join(go)

parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true', help='Fail if generated files differ from schema')
args = parser.parse_args()
swift, go = generate()
go = subprocess.run(['gofmt'], input=go, text=True, check=True, capture_output=True).stdout
outputs = {SWIFT:swift, GO:go}
if args.check:
    stale = [str(path.relative_to(ROOT)) for path, value in outputs.items() if not path.exists() or path.read_text() != value]
    if stale:
        raise SystemExit('Stale generated files: ' + ', '.join(stale))
else:
    for path, value in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(value)

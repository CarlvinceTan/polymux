#!/usr/bin/env python3
"""Generate the Go and TypeScript wire representations from polymux.schema.json."""
import argparse
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCHEMA = json.loads((ROOT / 'contracts/polymux.schema.json').read_text())
GO = ROOT / 'apps/server/internal/contract/types.go'
TS = ROOT / 'apps/tauri/src/lib/api/contract.ts'

def ts_type(field):
    if '$ref' in field:
        name = field['$ref'].split('/')[-1]
        return 'WireError' if name == 'Error' else name
    kind = field['type']
    if kind == 'array':
        item = ts_type(field['items'])
        return f'Array<{item}>' if '|' in item else f'{item}[]'
    if kind == 'object':
        return f'Record<string, {ts_type(field["additionalProperties"])}>'
    return {'string':'string','integer':'number','number':'number','boolean':'boolean'}[kind]

def ts_enums(name, fields):
    lines = []
    for key, field in fields.items():
        values = [value for value in field.get('enum', []) if value]
        if not values:
            continue
        alias = f'{name}{key[0].upper() + key[1:]}'
        lines.append(f'export type {alias} = ' + ' | '.join(json.dumps(value) for value in values) + ';')
    return lines

def ts_field_type(name, key, field):
    values = [value for value in field.get('enum', []) if value]
    if values:
        return f'{name}{key[0].upper() + key[1:]}'
    return ts_type(field)

def go_type(field):
    if '$ref' in field:
        return field['$ref'].split('/')[-1]
    if 'x-go-type' in field:
        return field['x-go-type']
    kind = field['type']
    if kind == 'array':
        return '[]' + go_type(field['items'])
    if kind == 'object':
        return 'map[string]' + go_type(field['additionalProperties'])
    return {'string':'string','integer':'int64','number':'float64','boolean':'bool'}[kind]

INITIALISMS = {'html': 'HTML', 'id': 'ID', 'url': 'URL', 'http': 'HTTP'}

def go_name(text):
    return ''.join(INITIALISMS.get(word, word[:1].upper() + word[1:]) for word in text.replace('.', '_').split('_'))

def go_enums(name, fields):
    lines = []
    for key, field in fields.items():
        values = [value for value in field.get('enum', []) if value]
        if values:
            lines.extend(f'\t{name}{go_name(key)}{go_name(value)} = "{value}"' for value in values)
    return ['const ('] + lines + [')', ''] if lines else []

def generate():
    go = ['// Code generated by contracts/generate.py; DO NOT EDIT.', 'package contract', '']
    ts = ['// Generated by contracts/generate.py. Edit polymux.schema.json instead.']
    for original, definition in SCHEMA['$defs'].items():
        name = 'WireError' if original == 'Error' else original
        fields = definition['properties']
        required = definition['required']
        go.append(f'type {original} struct {{')
        ts.extend(ts_enums(name, fields))
        ts.append(f'export interface {name} {{')
        for key, field in fields.items():
            optional = key not in required
            gt = go_type(field)
            if optional and field.get('type') not in ('array', 'object') and not field.get('x-go-value', False):
                gt = '*' + gt
            gname = key[0].upper() + key[1:]
            if key == 'id':
                gname = 'ID'
            if key == 'url':
                gname = 'URL'
            go.append(f'\t{gname} {gt} `json:"{key}' + (',omitempty' if optional else '') + '"`')
            tt = ts_field_type(name, key, field)
            ts.append(f'  {key}{"?" if optional else ""}: {tt};')
        go.extend(['}', ''])
        go.extend(go_enums(original, fields))
        ts.extend(['}', ''])
    return '\n'.join(go), '\n'.join(ts)

parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true', help='Fail if generated files differ from schema')
args = parser.parse_args()
go, ts = generate()
go = subprocess.run(['gofmt'], input=go, text=True, check=True, capture_output=True).stdout
outputs = {GO:go, TS:ts}
if args.check:
    stale = [str(path.relative_to(ROOT)) for path, value in outputs.items() if not path.exists() or path.read_text() != value]
    if stale:
        raise SystemExit('Stale generated files: ' + ', '.join(stale))
else:
    for path, value in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(value)

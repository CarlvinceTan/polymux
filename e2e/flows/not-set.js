// Without a default model a new bot is Not set, follows whichever providers are connected, and can return to Not set.
let app = await cua.getApp(APP);
const host = await app.getState({ query: "Settings", include_screenshot: false });
await app.click({ role: "button", name: "New chat" });
app = await pick(app, "New Bot");
await app.typeText("Auto QA", { role: "textfield", name: "Name" });
await app.click({ role: "button", name: "Create" });
await app.waitFor({ role: "button", name: "Edit Auto QA’s profile", timeout_ms: 10000 });
await app.click({ role: "button", name: "Edit Auto QA’s profile" });
await app.click({ role: "button", name: "Capabilities" });
await app.waitFor({ role: "button", name: "Model", value: "Not set", timeout_ms: 10000 });
await app.click({ role: "button", name: "Close side panel" });
await app.click({ role: "button", name: "Settings" });
await app.click({ role: "button", name: "Models" });
await app.waitFor({ role: "button", name: "Default model", value: "Server default", timeout_ms: 5000 });
await app.click({ role: "button", name: "Add provider" });
await app.waitFor({ role: "button", name: "Add custom provider" });
const state = await app.getState({ query: "Add custom provider", tree_format: "elements", max_elements: 800, timeout_ms: 5000, include_screenshot: false });
const buttons = state.elements.filter(row => row.role === "AXButton" && row.label === "Add custom provider");
if (state.truncated || buttons.length !== 1) throw new Error("Custom provider action lookup is incomplete or ambiguous");
await app.click(buttons[0].element_token);
await app.setValue({ role: "textfield", name: "Name" }, "");
await app.typeText("Routing QA", { role: "textfield", name: "Name" });
await app.typeText("http://127.0.0.1:1/v1", { role: "textfield", name: "Base URL" });
await app.typeText("qa-model", { role: "textfield", name: "Model ID" });
await app.click({ role: "button", name: "Add" });
await app.click({ role: "button", name: "Save" });
await app.waitFor({ role: "button", name: "Edit Custom", timeout_ms: 10000 });
await app.click({ role: "button", name: "Close Settings" });
// The unreachable provider takes the next reply with no profile change.
await app.typeText("Routed to the provider", { role: "textfield", name: "Message" });
await app.pressKey("return", { role: "textfield", name: "Message" });
await app.waitFor({ role: "statictext", name: "No providers are available right now.", timeout_ms: 10000 });
await app.click({ role: "button", name: "Dismiss warning" });
await app.click({ role: "button", name: "Edit Auto QA’s profile" });
await app.click({ role: "button", name: "Capabilities" });
await app.click({ role: "button", name: "Model" });
await app.click({ role: "button", name: "Qa Model Custom" });
app = await cua.getApp({ pid: host.pid, windowId: host.window_id });
await app.waitFor({ role: "button", name: "Model", value: "Qa Model Routing QA", timeout_ms: 10000 });
await app.click({ role: "button", name: "Model" });
await app.click({ role: "button", name: "Not set" });
app = await cua.getApp({ pid: host.pid, windowId: host.window_id });
await app.waitFor({ role: "button", name: "Model", value: "Not set", timeout_ms: 10000 });
await app.click({ role: "button", name: "Close side panel" });
await app.click({ role: "button", name: "Settings" });
await app.click({ role: "button", name: "Models" });
await app.click({ role: "button", name: "Edit Custom" });
await app.waitFor({ role: "textfield", name: "Name", value: "Routing QA" });
await app.click({ role: "button", name: "Delete" });
await app.waitFor({ role: "button", name: "Select Routing QA", gone: true, timeout_ms: 5000 });
await app.click({ role: "button", name: "Close Settings" });
return "ok";

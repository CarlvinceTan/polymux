// Removing a provider explains the failure; an explicit profile remap preserves the bot and its history.
let app = await cua.getApp(APP);
const host = await app.getState({ query: "Settings", include_screenshot: false });
async function add(name) {
  await app.click({ role: "button", name: "Add provider" });
  await app.waitFor({ role: "button", name: "Add custom provider" });
  const state = await app.getState({ query: "Add custom provider", tree_format: "elements", max_elements: 800, timeout_ms: 5000, include_screenshot: false });
  const buttons = state.elements.filter(row => row.role === "AXButton" && row.label === "Add custom provider");
  if (state.truncated || buttons.length !== 1) throw new Error("Custom provider action lookup is incomplete or ambiguous");
  await app.click(buttons[0].element_token);
  await app.setValue({ role: "textfield", name: "Name" }, "");
  await app.typeText(name, { role: "textfield", name: "Name" });
  await app.typeText("http://127.0.0.1:1/v1", { role: "textfield", name: "Base URL" });
  await app.typeText("qa-model", { role: "textfield", name: "Model ID" });
  await app.click({ role: "button", name: "Add" });
  await app.click({ role: "button", name: "Save" });
  await app.waitFor({ role: "button", name: "Edit Custom", timeout_ms: 10000 });
}
await app.click({ role: "button", name: "Settings" });
await app.click({ role: "button", name: "Models" });
await add("Removed QA");
await app.click({ role: "button", name: "Model" });
await app.click({ role: "button", name: "Qa Model Custom" });

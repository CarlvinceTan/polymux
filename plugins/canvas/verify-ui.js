let app = await cua.getApp(APP);
const bot = "Map sample bot";
await app.click({ role: "button", name: "New chat" });
app = await pick(app, "New Bot");
await app.waitFor({ role: "textfield", name: "Name" });
await app.typeText(bot, { role: "textfield", name: "Name" });
await app.click({ role: "button", name: "Create" });
await app.waitFor({ role: "button", name: "Close New Bot", gone: true });
await app.click({ role: "button", name: "Settings" });
await app.click({ role: "button", name: "Plugins" });
await app.click({ role: "button", name: "Marketplace" });
await app.click({ role: "button", name: "Install Canvas" });
await app.click({ role: "button", name: "Install" });
await app.waitFor({ text: "Installed" });
await app.click({ role: "button", name: "Close Settings" });
await app.waitFor({ role: "button", name: "Canvas" });
await app.click({ role: "button", name: "Canvas" });
const node = { role: "checkbox", name: bot };
await app.waitFor(node);
await app.click(node);
await app.waitFor({ role: "heading", name: bot });
await app.click({ role: "button", name: "Close details" });
await app.waitFor({ role: "heading", name: bot, gone: true });

await app.click({ role: "checkbox", name: "Add node" });
await app.pressKey("return");
const title = { role: "textfield", name: "Title" };
await app.waitFor(title);
await app.pressKey("cmd+a", title);
await app.typeText("Plan next steps", title);
await app.waitFor({ ...title, value: "Plan next steps" });
await app.click({ role: "button", name: "Save" });
await app.waitFor({ role: "heading", name: "Plan next steps" });
await app.click({ role: "button", name: "Close details" });
await app.click({ role: "checkbox", name: "Draw wire" });
await app.click(node);
await app.click({ role: "checkbox", name: "Plan next steps" });
await app.waitFor({ role: "heading", name: "Connection" });
const label = { role: "textfield", name: "Label" };
await app.typeText("Leads to", label);
await app.waitFor({ ...label, value: "Leads to" });
await app.click({ role: "button", name: "Save" });
await app.waitFor({ role: "button", name: "Leads to" });
await app.click({ role: "button", name: "Undo" });
await app.waitFor({ role: "button", name: "Leads to", gone: true });
await app.click({ role: "button", name: "Redo" });
await app.waitFor({ role: "button", name: "Leads to" });
await app.click({ role: "button", name: bot });
await app.waitFor({ role: "checkbox", name: "Plan next steps", gone: true });
await app.click({ role: "button", name: "Canvas" });
await app.waitFor({ role: "checkbox", name: "Plan next steps" });
await app.waitFor({ role: "button", name: "Leads to" });
return "Canvas installed, edited, undid and redid a wire, and reopened the saved board";

// Capture the published DS Bot website's prop geometry, without executing its application.
import vm from 'node:vm'
import { createHash } from 'node:crypto'
import { writeFile } from 'node:fs/promises'
const response = await fetch('https://dsbot.app/')
if (!response.ok) throw new Error(`dsbot.app: ${response.status}`)
const html = await response.text()
const start = html.indexOf('var Ei=') + 7
if (start < 7 || html[start] !== '{') throw new Error('Website prop catalog changed; inspect source before updating')
let end = start, depth = 0, quote = false, escape = false
for (; end < html.length; end++) {
  const c = html[end]
  if (quote) { if (escape) escape=false; else if(c==='\\') escape=true; else if(c==='"') quote=false; continue }
  if(c==='"'){quote=true;continue}
  if(c==='{') depth++
  if(c==='}' && --depth===0) {end++;break}
}
const props = vm.runInNewContext('('+html.slice(start,end)+')', Object.create(null), {timeout:1000})
const names = { type:'keyboard', write:'writing', chart:'chart', read:'reading', mail:'mail', plan:'planning', card:'card', plane:'plane' }
let out = `// Geometry reference: https://dsbot.app/, SHA-256 ${createHash('sha256').update(html).digest('hex')}.\n`
out += '// Generated by scripts/avatar-props.mjs; native motion and solid-colour adaptation.\nimport Foundation\n\nlet PROP_ART: [WorkProp: [PropShape]] = [\n'
for (const [key,name] of Object.entries(names)) {
  out+=`    .${name}: [\n`
  for (const group of props[key].groups) for (const p of group.parts) {
    for (const [path,color,opacity] of [[p.body,p.fill,p.opacity??1],...(p.paints??[]),[p.shade,'#000000',.14],[p.light,'#FFFFFF',.16]]) {
      if(!path)continue
      const commands=[...new Set(path.match(/[a-zA-Z]/g))]
      if(commands.some(c=>!['M','l','z'].includes(c)))throw new Error(`Unsupported path commands: ${commands}`)
      out+=`        PropShape(${JSON.stringify(path)}, color: ${JSON.stringify(color)}, alpha: ${opacity}, group: ${JSON.stringify(group.cls??'')}, part: ${JSON.stringify(p.cls??'')}),\n`
    }
  }
  out+='    ],\n'
}
out+=']\n'
await writeFile(new URL('../packages/AvatarKit/Sources/AvatarKit/PropData.swift',import.meta.url),out)
